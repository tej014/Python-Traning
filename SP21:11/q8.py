# Q8. Set Operations
# Topic: Set
# Create two sets:
# A = {1, 2, 3, 4, 5}B = {4, 5, 6, 7, 8}
# Find:
# 1. Union of A and B.
# 2. Intersection of A and B.
# 3. Difference between A and B.
# 4. Difference between B and A.

A = {1, 2, 3, 4, 5}
B = {4, 5, 6, 7, 8}
print(A.union(B))
print(A.intersection(B))
print(A.difference(B))
print(B.difference(A))